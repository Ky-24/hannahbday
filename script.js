const intro = document.getElementById("intro");
const messagesScreen = document.getElementById("messages");
const lettersScreen = document.getElementById("lettersScreen");
const finalScreen = document.getElementById("finalScreen");

const startBtn = document.getElementById("startBtn");
const continueBtn = document.getElementById("continueBtn");

const message = document.getElementById("message");

const counter = document.getElementById("counter");
const letterTitle = document.getElementById("letterTitle");
const letterBody = document.getElementById("letterBody");

const letterVerse = document.getElementById("letterVerse");
const verseReference = document.getElementById("verseReference");

const pageNumber = document.getElementById("pageNumber");
const memoryPhoto = document.getElementById("memoryPhoto");

const previousBtn = document.getElementById("previousBtn");
const nextBtn = document.getElementById("nextBtn");

const birthdayVideo = document.getElementById("birthdayVideo");

let currentLetter = 0;
let messageIndex = 0;
let messageTimer = null;


// ========================================
// OPENING MESSAGES
// ========================================

const openingMessages = [

    "Hi, my Baby!",

    "Happy Birthday my love love",

    "Surpriseeeee!!!!!!!!♡",

];


// ========================================
// SCREEN NAVIGATION
// ========================================

function showScreen(screen) {

    document.querySelectorAll(".screen").forEach(item => {
        item.classList.remove("active");
    });

    screen.classList.add("active");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


// ========================================
// OPENING MESSAGE ANIMATION
// ========================================

function stopMessageSequence() {

    if (messageTimer !== null) {
        clearInterval(messageTimer);
        messageTimer = null;
    }

}


function showOpeningMessage() {

    message.textContent = openingMessages[messageIndex];

    continueBtn.classList.toggle(
        "hidden",
        messageIndex !== openingMessages.length - 1
    );

}


function startMessageSequence() {

    stopMessageSequence();

    messageIndex = 0;

    showScreen(messagesScreen);

    showOpeningMessage();

    messageTimer = setInterval(() => {

        if (!messagesScreen.classList.contains("active")) {

            stopMessageSequence();
            return;

        }

        if (messageIndex < openingMessages.length - 1) {

            messageIndex++;

            showOpeningMessage();

        } else {

            stopMessageSequence();

        }

    }, 1800);

}


startBtn.addEventListener("click", startMessageSequence);


// ========================================
// OPEN LETTERS
// ========================================

continueBtn.addEventListener("click", () => {

    stopMessageSequence();

    showScreen(lettersScreen);

    showLetter(0);

});


// ========================================
// DISPLAY LETTER, PHOTO, AND VERSE
// ========================================

function showLetter(index) {

    currentLetter = index;

    const letter = letters[index];
    const verse = bibleVerses[index];


    // LETTER NUMBER

    counter.textContent =
        `LETTER ${String(index + 1).padStart(2, "0")} OF 24`;

    pageNumber.textContent =
        `${String(index + 1).padStart(2, "0")} / 24`;


    // LETTER CONTENT

    letterTitle.textContent = letter.title;

    letterBody.textContent = letter.body;


    // BIBLE VERSE

    letterVerse.textContent = `“${verse.verse}”`;

    verseReference.textContent = verse.reference;


    // PHOTO

    memoryPhoto.style.opacity = "0";

    memoryPhoto.onload = () => {

        memoryPhoto.style.opacity = "1";

    };

    memoryPhoto.onerror = () => {

        memoryPhoto.style.opacity = "1";

        memoryPhoto.alt = `Photo missing: ${letter.photo}`;

        console.warn(`Could not load image: ${letter.photo}`);

    };

    memoryPhoto.src = letter.photo;

    memoryPhoto.alt = letter.title;


    // PREVIOUS BUTTON

    previousBtn.style.visibility =
        index === 0 ? "hidden" : "visible";


    // NEXT BUTTON

    nextBtn.textContent =
        index === letters.length - 1 ? "finish ♡" : "next →";


    // ANIMATION

    const card = document.getElementById("letterCard");

    card.animate(
        [
            {
                opacity: 0,
                transform: "translateY(12px) rotate(-2deg)"
            },
            {
                opacity: 1,
                transform: "translateY(0) rotate(-1deg)"
            }
        ],
        {
            duration: 450,
            easing: "ease-out"
        }
    );

}


// ========================================
// PREVIOUS LETTER
// ========================================

previousBtn.addEventListener("click", () => {

    if (currentLetter > 0) {

        showLetter(currentLetter - 1);

    }

});


// ========================================
// NEXT LETTER / FINISH
// ========================================

nextBtn.addEventListener("click", () => {

    if (currentLetter < letters.length - 1) {

        showLetter(currentLetter + 1);

    } else {

        showScreen(finalScreen);

    }

});


// ========================================
// BACK TO START
// ========================================

function backToStart() {

    stopMessageSequence();

    if (birthdayVideo) {

        birthdayVideo.pause();

    }

    messageIndex = 0;

    message.textContent = "";

    continueBtn.classList.add("hidden");

    showScreen(intro);

}


document.getElementById("messageBackBtn")
    .addEventListener("click", backToStart);

document.getElementById("backStartBtn")
    .addEventListener("click", backToStart);

document.getElementById("backStartFinalBtn")
    .addEventListener("click", backToStart);


// ========================================
// READ LETTERS AGAIN
// ========================================

document.getElementById("restartBtn").addEventListener("click", () => {

    if (birthdayVideo) {

        birthdayVideo.pause();

        birthdayVideo.currentTime = 0;

    }

    showScreen(lettersScreen);

    showLetter(0);

});


// ========================================
// FLOATING HEARTS
// ========================================

function createHeart() {

    const heart = document.createElement("span");

    heart.className = "floating-heart";

    heart.textContent = Math.random() > 0.5 ? "♡" : "♥";

    heart.style.left = Math.random() * 100 + "vw";

    heart.style.fontSize =
        (12 + Math.random() * 20) + "px";

    heart.style.animationDuration =
        (6 + Math.random() * 7) + "s";

    document.getElementById("hearts").appendChild(heart);

    setTimeout(() => {

        heart.remove();

    }, 14000);

}


setInterval(createHeart, 550);